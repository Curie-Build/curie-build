#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MavenManagedDependency {
    pub group_id: String,
    pub artifact_id: String,
    pub version: String,
    pub is_import: bool,
}

/// A `<repositories><repository>` entry, from a `[[repositories]]` table in
/// `Curie.toml`. Maven repositories are global to the POM, so every
/// `[[repositories]]` entry becomes a `<repository>` regardless of which
/// dependencies select it via `repository = "id"` (divergence #5 in
/// `_design/MAVEN-SYNC.md`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MavenRepository {
    pub id: String,
    pub name: String,
    pub url: String,
}

/// A generic XML element used to render plugin `<configuration>` blocks
/// without a dedicated Rust type per plugin.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum XmlNode {
    /// `<name>text</name>` — text is escaped on render.
    Text(String, String),
    /// `<name>child1 child2 ...</name>`
    Element(String, Vec<XmlNode>),
    /// `<name attr="value">child1 child2 ...</name>`, or
    /// `<name attr="value"/>` when `children` is empty — used for
    /// maven-shade-plugin's `<transformer implementation="...">`.
    ElementWithAttr(String, (String, String), Vec<XmlNode>),
}

impl XmlNode {
    pub fn text(name: impl Into<String>, value: impl Into<String>) -> Self {
        XmlNode::Text(name.into(), value.into())
    }

    pub fn element(name: impl Into<String>, children: Vec<XmlNode>) -> Self {
        XmlNode::Element(name.into(), children)
    }

    pub fn element_with_attr(name: impl Into<String>, attr: (impl Into<String>, impl Into<String>), children: Vec<XmlNode>) -> Self {
        XmlNode::ElementWithAttr(name.into(), (attr.0.into(), attr.1.into()), children)
    }
}

/// A `<plugin>` entry under `<build><plugins>`.
#[derive(Debug, Clone, Default)]
