/// A `<dependency>` entry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MavenDependency {
    pub group_id: String,
    pub artifact_id: String,
    /// `None` when the version is supplied by an imported BOM (Curie's
    /// `version = ""`) — the `<version>` element is omitted.
    pub version: Option<String>,
    pub scope: Option<String>,
    /// `(groupId, artifactId)` pairs from `exclusions = ["g:a", ...]`.
    pub exclusions: Vec<(String, String)>,
}

/// One entry of the `pinTransitive` resolved dependency closure
/// (`group:artifact -> version`), materialized into
/// `<dependencyManagement>` when `[maven] pinTransitive = true`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct PinnedDependency {
    pub group_id: String,
    pub artifact_id: String,
    pub version: String,
}

/// A `<dependencyManagement><dependencies>` entry: either an imported BOM
/// (`<type>pom</type><scope>import</scope>`) or an explicit managed version
/// (from `pinTransitive`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MavenManagedDependency {
    pub group_id: String,
    pub artifact_id: String,
    pub version: String,
    pub is_import: bool,
}

/// A generic XML element used to render plugin `<configuration>` blocks
/// without a dedicated Rust type per plugin.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum XmlNode {
    /// `<name>text</name>` — text is escaped on render.
    Text(String, String),
    /// `<name>child1 child2 ...</name>`
    Element(String, Vec<XmlNode>),
}

impl XmlNode {
    pub fn text(name: impl Into<String>, value: impl Into<String>) -> Self {
        XmlNode::Text(name.into(), value.into())
    }

    pub fn element(name: impl Into<String>, children: Vec<XmlNode>) -> Self {
        XmlNode::Element(name.into(), children)
    }
}

/// A `<plugin>` entry under `<build><plugins>`.
#[derive(Debug, Clone, Default)]
pub struct MavenPlugin {
    /// `None` renders as [`DEFAULT_PLUGIN_GROUP_ID`].
    pub group_id: Option<String>,
    pub artifact_id: String,
    pub version: String,
    pub configuration: Vec<XmlNode>,
    pub executions: Vec<MavenExecution>,
}

/// An `<execution>` entry under a plugin's `<executions>`.
#[derive(Debug, Clone, Default)]
pub struct MavenExecution {
    pub id: Option<String>,
    pub phase: Option<String>,
    pub goals: Vec<String>,
    pub configuration: Vec<XmlNode>,
}

/// The full model rendered into a `pom.xml`.
#[derive(Debug, Clone, Default)]
pub struct MavenProject {
    pub group_id: String,
    pub artifact_id: String,
    pub version: String,
    pub packaging: String,
    pub properties: Vec<(String, String)>,
    pub layout: MavenLayout,
    pub dependencies: Vec<MavenDependency>,
    pub managed_dependencies: Vec<MavenManagedDependency>,
    pub plugins: Vec<MavenPlugin>,
}

