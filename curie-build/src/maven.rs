//! Maven `pom.xml` generation for `curie maven sync` (see
//! `_design/MAVEN-SYNC.md`).
//!
//! Maps a Curie [`Descriptor`] plus the on-disk source layout to a `pom.xml`
//! such that `mvn verify` produces the same build outputs as `curie build`.
//! The module is split into three layers:
//!
//! - [`discover_layout`] inspects the project directory for source/test/
//!   resource roots, mirroring the layouts `compile.rs`/`test.rs` support.
//! - [`build_project`] + [`render`] turn a descriptor (+ layout) into a
//!   [`MavenProject`] model and then into deterministic XML.
//! - [`sync_pom`] wraps both with fingerprint-based incremental writes and
//!   the "don't clobber a hand-written pom.xml" safety check.

use crate::compile::{flat_package_src_dirs, flat_package_test_dirs};
use crate::descriptor::{Descriptor, DependencyValue};
use crate::incremental::walk_files;
use anyhow::{Context, Result};
use quick_xml::events::{BytesDecl, BytesEnd, BytesStart, BytesText, Event};
use quick_xml::Writer;
use sha2::{Digest, Sha256};
use std::collections::BTreeSet;
use std::io::Cursor;
use std::path::{Path, PathBuf};

/// `groupId` fallback for projects that don't declare one in `Curie.toml`.
pub const GENERATED_GROUP_ID: &str = "curie.generated";

/// Maven's reproducible-builds property; matches `jar.rs::epoch()`.
pub const OUTPUT_TIMESTAMP: &str = "2024-01-01T00:00:00Z";

/// Bump to force every generated `pom.xml` to be regenerated even when
/// none of the other fingerprint inputs changed.
pub const SCHEMA_VERSION: u32 = 1;

/// Human-readable line written into every generated POM, immediately above
/// the `curie-maven-fingerprint:` line.
const GENERATED_MARKER: &str = "Generated by curie maven sync from Curie.toml — DO NOT EDIT.";
const FINGERPRINT_PREFIX: &str = "curie-maven-fingerprint: ";

/// Default `<groupId>` for plugins declared without one (the standard Maven
/// plugin prefix).
const DEFAULT_PLUGIN_GROUP_ID: &str = "org.apache.maven.plugins";

/// Pinned versions of every Maven plugin the generator emits.  Versions are
/// part of the reproducibility surface: bump deliberately, alongside
/// [`SCHEMA_VERSION`].  Checked against Maven Central on 2026-06-11.
pub mod plugin_versions {
    pub const COMPILER: &str = "3.15.0";
    pub const SUREFIRE: &str = "3.5.6";
    pub const JAR: &str = "3.5.0";
    pub const SHADE: &str = "3.6.2";
    pub const DEPENDENCY: &str = "3.11.0";
    pub const BUILD_HELPER: &str = "3.6.0";
    pub const GMAVENPLUS: &str = "4.2.0";
    pub const JACOCO: &str = "0.8.13";
}

const BUILD_HELPER_GROUP_ID: &str = "org.codehaus.mojo";
const BUILD_HELPER_ARTIFACT_ID: &str = "build-helper-maven-plugin";

